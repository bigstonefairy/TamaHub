// Nombre de la especie en el idioma activo (el ingles vive en DEX_TBL).
const char *dexName(int16_t dex) {
  if (dex < 1 || dex > DEX_COUNT) return "?";
  return (gLang == LANG_KO) ? DEX_NAME_KO[dex] : DEX_TBL[dex].name;
}

// El idioma se guarda en "lang2" para no reinterpretar el "lang" de versiones
// anteriores, donde 1 era ingles: aqui 1 es coreano.
void loadLang() {
  Preferences p;
  p.begin("idledigi", true);
  uint8_t v = p.getUChar("lang2", 0xFF);
  p.end();
  if (v < LANG_COUNT) {
    gLang = (Lang)v;
    return;
  }
  gLang = LANG_DEFAULT;
  p.begin("idledigi", false);
  p.putUChar("lang2", (uint8_t)gLang);
  p.end();
}

void setLang(Lang l) {
  if (l >= LANG_COUNT) return;
  gLang = l;
  Preferences p;
  p.begin("idledigi", false);
  p.putUChar("lang2", (uint8_t)l);
  p.end();
}
