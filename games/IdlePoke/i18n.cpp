const char *dexName(int16_t dex) {
  if (dex < 1 || dex > DEX_COUNT) return "?";
  uint8_t lang = (gLang < LANG_COUNT) ? (uint8_t)gLang : LANG_DEFAULT;
  if (lang >= DEX_LANG_COUNT) lang = LANG_DEFAULT;
  return DEX_NAMES[lang][dex];
}
