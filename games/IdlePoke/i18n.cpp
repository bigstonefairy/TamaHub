const char *medalDesc(int i)  { return MED_DSC[gLang][i]; }

// El idioma se guarda en "lang2" para no reinterpretar el "lang" de versiones
// anteriores, donde 1 era ingles: aqui 1 es coreano. Al actualizar, cualquier
// valor viejo se queda en ingles una sola vez y se reescribe en la clave nueva.
void loadLang() {
  Preferences p;
  p.begin("idlepoke", true);
  uint8_t v = p.getUChar("lang2", 0xFF);
  p.end();
  if (v < LANG_COUNT) {
    gLang = (Lang)v;
    return;
  }
  gLang = LANG_DEFAULT;
  p.begin("idlepoke", false);
  p.putUChar("lang2", (uint8_t)gLang);
  p.end();
}

void setLang(Lang l) {
  if (l >= LANG_COUNT) return;
  gLang = l;
  Preferences p;
  p.begin("idlepoke", false);
  p.putUChar("lang2", (uint8_t)l);
  p.end();
}
