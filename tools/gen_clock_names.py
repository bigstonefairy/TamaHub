#!/usr/bin/env python3
"""Generate apps/TamaClock/monnames.h from the two games' dex tables.

TamaClock shares the games' SD sprite packs and therefore their dex numbers,
but it never links the games' sources.  The label under the creature needs the
species name, so this script copies just the name column out of
games/TamaPoke/dex.h and games/TamaDigi/dex.h into a small standalone header.

Run it after changing either roster:

    python tools/gen_clock_names.py
"""

from __future__ import annotations

import os
import re
import sys

HERE = os.path.dirname(os.path.abspath(__file__))
ROOT = os.path.dirname(HERE)
OUT = os.path.join(ROOT, "apps", "TamaClock", "monnames.h")

SOURCES = [
    ("POKE_MON_NAMES", os.path.join(ROOT, "games", "TamaPoke", "dex.h")),
    ("DIGI_MON_NAMES", os.path.join(ROOT, "games", "TamaDigi", "dex.h")),
]

ROW = re.compile(r'^\s*\{\s*"((?:[^"\\]|\\.)*)"')


def names(path: str) -> list[str]:
    out: list[str] = []
    inside = False
    with open(path, encoding="utf-8") as f:
        for line in f:
            if not inside:
                if "DEX_TBL[" in line and "=" in line:
                    inside = True
                continue
            if line.strip() == "};":
                break
            m = ROW.match(line)
            if m:
                out.append(m.group(1))
    if not out:
        raise SystemExit(f"{path}: no DEX_TBL rows found")
    # Row 0 is the unused placeholder ("?" in both games).
    return out


def emit() -> str:
    lines = [
        "// GENERATED by tools/gen_clock_names.py - do not edit.",
        "//",
        "// Just the species-name column of each game's dex table, indexed by the",
        "// same dex number the SD packs use (index 0 is unused).",
        "#pragma once",
        "",
    ]
    for table, path in SOURCES:
        rows = names(path)
        lines.append(f"static const char *const {table}[{len(rows)}] = {{")
        for i, name in enumerate(rows):
            lines.append(f'    "{name}",  // {i}')
        lines.append("};")
        lines.append("")
    return "\n".join(lines)


def main() -> int:
    text = emit()
    with open(OUT, "w", encoding="utf-8", newline="\n") as f:
        f.write(text)
    print(f"wrote {OUT}")
    for table, path in SOURCES:
        print(f"  {table}: {len(names(path)) - 1} entries")
    return 0


if __name__ == "__main__":
    sys.exit(main())
